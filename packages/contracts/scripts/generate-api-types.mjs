import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageRoot, "../..");

const INPUTS = Object.freeze({
  publicViewsSchema: "contracts/api/public-views.schema.json",
  eventsSchema: "contracts/api/events.schema.json",
  reviewFixture: "contracts/api/fixtures/review-view.json",
  eventFixture: "contracts/api/fixtures/run-state-event.json",
});

const OUTPUTS = Object.freeze({
  api: "packages/contracts/src/generated/api.ts",
  fixtures: "packages/contracts/src/generated/fixtures.ts",
});

const COMPILE_OPTIONS = Object.freeze({
  additionalProperties: false,
  bannerComment: "",
  enableConstEnums: false,
  format: true,
  strictIndexSignatures: true,
  unreachableDefinitions: false,
  unknownAny: false,
});

function pascalCaseTitle(title) {
  return String(title)
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .map((part) => `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join("");
}

function eventTypeName(schema, keyNameFromDefinition) {
  if (keyNameFromDefinition !== undefined) return keyNameFromDefinition;
  if (schema.title === "EventEnvelope") return "EventEnvelope";
  if (schema.title !== undefined) return `Event${pascalCaseTitle(schema.title)}`;
  return undefined;
}

function readText(relativePath) {
  return readFileSync(resolve(repoRoot, relativePath), "utf8");
}

function readJson(relativePath) {
  return JSON.parse(readText(relativePath));
}

function withRootTitle(schema, title) {
  return { ...schema, title };
}

function normalizeCompiledTypes(source) {
  return source.trimEnd().replace(/\n{3,}/g, "\n\n");
}

export async function generateApiSource() {
  const publicViewsSchema = withRootTitle(readJson(INPUTS.publicViewsSchema), "PublicView");
  const eventsSchema = withRootTitle(readJson(INPUTS.eventsSchema), "EventEnvelope");
  const publicViewsSource = await compile(publicViewsSchema, "PublicView", COMPILE_OPTIONS);
  const eventsSource = await compile(eventsSchema, "EventEnvelope", { ...COMPILE_OPTIONS, customName: eventTypeName });
  return [
    "/* Generated by packages/contracts/scripts/generate-api-types.mjs. */",
    "/* Do not edit by hand. */",
    "",
    normalizeCompiledTypes(publicViewsSource),
    "",
    normalizeCompiledTypes(eventsSource),
    "",
  ].join("\n");
}

export function generateFixturesSource() {
  const reviewFixture = readJson(INPUTS.reviewFixture);
  const eventFixture = readJson(INPUTS.eventFixture);
  return [
    "/* Generated by packages/contracts/scripts/generate-api-types.mjs. */",
    "/* Do not edit by hand. */",
    "",
    'import type { EventEnvelope, ReviewView } from "./api.js";',
    "",
    `export const reviewFixture = ${JSON.stringify(reviewFixture, null, 2)} as const satisfies ReviewView;`,
    "",
    `export const eventFixture = ${JSON.stringify(eventFixture, null, 2)} as const satisfies EventEnvelope;`,
    "",
  ].join("\n");
}

export async function generateContractSources() {
  return {
    api: await generateApiSource(),
    fixtures: generateFixturesSource(),
  };
}

export function readCommittedContractSources() {
  return {
    api: readText(OUTPUTS.api),
    fixtures: readText(OUTPUTS.fixtures),
  };
}

function writeContractSources(sources) {
  writeFileSync(resolve(repoRoot, OUTPUTS.api), sources.api);
  writeFileSync(resolve(repoRoot, OUTPUTS.fixtures), sources.fixtures);
}

function reportDrift(expected, actual) {
  for (const key of Object.keys(expected)) {
    if (expected[key] !== actual[key]) {
      console.error(`GENERATED_${key.toUpperCase()}_DRIFT`);
    }
  }
}

export async function runGenerateCommand(argv = process.argv.slice(2)) {
  const sources = await generateContractSources();
  if (argv.includes("--write")) {
    writeContractSources(sources);
    return 0;
  }
  if (argv.includes("--check")) {
    let committed;
    try {
      committed = readCommittedContractSources();
    } catch {
      console.error("GENERATED_CONTRACT_SOURCE_MISSING");
      return 1;
    }
    if (sources.api !== committed.api || sources.fixtures !== committed.fixtures) {
      reportDrift(sources, committed);
      return 1;
    }
    return 0;
  }
  console.error("USAGE: generate-api-types.mjs --write|--check");
  return 2;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = await runGenerateCommand();
}
